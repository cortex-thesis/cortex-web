import { test, expect } from '@playwright/test'
const states = ['focused', 'relaxed', 'distracted', 'overstimulated']
const years = [{ value: '2027–2028', label: '2027–2028', is_active: true }, { value: '2026–2027', label: '2026–2027', is_archived: true }, { value: '2030–2031', label: '2030–2031' }]
async function fixture(page, admin = false) {
  const calls = []
  await page.route('**/api/**', async route => {
    const request = route.request(), url = new URL(request.url()), path = url.pathname
    let value = {}
    if (path === '/api/auth/me/') value = { id: 'year-user', name: 'Year User', role: admin ? 'admin' : 'teacher', admin_scope: admin ? 'school' : 'none' }
    else if (path === '/api/notifications/') value = { notifications: [], unread_count: 0 }
    else if (path === '/api/sync/status/') value = { enabled: false }
    else if (path === '/api/class-sessions/') value = { sessions: [] }
    else if (path === '/api/admin/school-years/') { if (request.method() === 'POST') calls.push(request.postDataJSON()); value = { school_years: years } }
    else if (path === '/api/admin/dashboard/') value = { administrator: { school: 'Test school' }, classes: [] }
    else if (path.startsWith('/api/teacher/reports/')) {
      calls.push(url.searchParams.get('school_year'))
      const selected = url.searchParams.get('school_year') || '2027–2028', empty = selected === '2030–2031'
      value = { school_years: years, selected_school_year: selected, classes: empty ? [] : [{ id: 1, name: 'Year class' }], selected_class_id: empty ? null : 1, class_name: empty ? null : 'Year class', students: [], sessions: [], school_year: selected, range: 'month', start_date: null, end_date: '2026-10-16', prepared_by: 'Year User',
        state_distribution: Object.fromEntries(states.map(state => [state, 25])), summary: { sessions: 0, participating_students: 0, average_focus_percentage: 0, focused_duration_seconds: 0, total_duration_seconds: 0, mode_changes: 0, tasks_completed: 0 }, generated_at: '2026-10-16T01:00:00Z', lessons: [], overall: { session_count: 0, sample_count: 0, first_sample_at: null, last_sample_at: null, states: Object.fromEntries(states.map(state => [state, { percentage: 25, samples: 0, average_confidence: 0 }])) } }
    }
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify(value) })
  })
  return calls
}
test('year filters reach both reports and survive navigation and reload', async ({ page }) => {
  const calls = await fixture(page); await page.goto('/teacher/reports')
  await expect(page.getByLabel('School year', { exact: true })).toHaveValue('2027–2028')
  await page.getByLabel('School year', { exact: true }).selectOption('2026–2027')
  await expect(page.getByRole('heading', { name: 'Year class', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Advanced reports', exact: true }).click()
  await expect(page.getByLabel('School year', { exact: true })).toHaveValue('2026–2027')
  await page.reload(); await expect(page.getByLabel('School year', { exact: true })).toHaveValue('2026–2027')
  await page.getByRole('button', { name: 'General report' }).click()
  await expect(page.getByRole('heading', { name: 'Class engagement report', exact: true })).toBeVisible()
  await page.getByLabel('School year', { exact: true }).selectOption('2030–2031')
  await expect(page.getByRole('heading', { name: 'No classes for this school year' })).toBeVisible()
  expect(calls).toContain('2026–2027'); expect(calls).toContain('2030–2031')
})
for (const report of ['/teacher/reports', '/teacher/reports/advanced']) {
  test(`${report}: tooltips support hover, keyboard focus and Escape`, async ({ page }) => {
    await fixture(page); await page.goto(report)
    for (const state of states) {
      const trigger = page.getByRole('button', { name: `About ${state}`, exact: true }).first()
      await trigger.hover()
      const tooltip = page.locator(`[id="${await trigger.getAttribute('aria-describedby')}"]`)
      await expect(tooltip).toBeVisible(); await expect(tooltip).toContainText('EEG-derived pattern')
      await trigger.focus(); await page.keyboard.press('Escape'); await expect(tooltip).toBeHidden()
      await page.mouse.move(0, 0); await trigger.blur(); await trigger.focus(); await expect(tooltip).toBeVisible()
      await trigger.click(); await expect(tooltip).toBeVisible(); await page.keyboard.press('Escape')
    }
    await expect(page.getByText('These states are EEG-derived estimates generated by Cortex and are not clinical assessments.')).toBeVisible()
  })
}
for (const report of ['/teacher/reports', '/teacher/reports/advanced']) {
test(`${report}: touch explanations stay within the mobile viewport and dismiss`, async ({ browser }) => {
  const context = await browser.newContext({ hasTouch: true, viewport: { width: 390, height: 844 } })
  const page = await context.newPage(); await fixture(page); await page.goto(report)
  for (const state of states) {
    const trigger = page.getByRole('button', { name: `About ${state}`, exact: true }); await trigger.tap()
    const tooltip = page.locator(`[id="${await trigger.getAttribute('aria-describedby')}"]`)
    await expect(tooltip).toBeVisible(); const box = await tooltip.boundingBox()
    expect(box.x).toBeGreaterThanOrEqual(0); expect(box.x + box.width).toBeLessThanOrEqual(390)
    expect(box.y).toBeGreaterThanOrEqual(0); expect(box.y + box.height).toBeLessThanOrEqual(844)
    if (state === 'overstimulated') await page.screenshot({ path: `../.runtime/tooltip-mobile-${report.endsWith('advanced') ? 'advanced' : 'general'}.png` })
    await page.getByRole('heading', { name: report.endsWith('advanced') ? 'Advanced reports' : 'Class engagement report', exact: true }).tap(); await expect(tooltip).toBeHidden()
  }
  await context.close()
})
}
test('administrator must confirm year actions and cannot archive the active year', async ({ page }) => {
  const calls = await fixture(page, true); await page.goto('/school-admin/dashboard')
  const section = page.getByRole('region', { name: 'School year management' }); await expect(section).toBeVisible()
  const active = section.locator('div').filter({ has: page.getByText('2027–2028 (Active)', { exact: true }) }).first()
  await expect(active.getByRole('button', { name: 'Archive school year' })).toBeDisabled()
  page.once('dialog', dialog => { expect(dialog.message()).toContain('2026–2027'); void dialog.dismiss() })
  await section.getByRole('button', { name: 'Restore school year' }).click(); expect(calls).toEqual([])
  page.once('dialog', dialog => { void dialog.accept() }); await section.getByRole('button', { name: 'Restore school year' }).click()
  await expect.poll(() => calls.length).toBe(1); expect(calls[0]).toEqual({ name: '2026–2027', action: 'restore', confirmed: true })
})
