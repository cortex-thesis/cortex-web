import { useEffect, useId, useRef, useState } from 'react'
import { createPortal } from 'react-dom'
import { Info } from 'lucide-react'
import styles from './CognitiveStateInfo.module.css'

const descriptions = {
  focused: 'The system classified the EEG-derived pattern as associated with focused engagement.',
  relaxed: 'The system classified the EEG-derived pattern as associated with a calmer state.',
  distracted: 'The system classified the EEG-derived pattern as associated with reduced task-focused engagement.',
  overstimulated: 'The system classified the EEG-derived pattern as associated with heightened stimulation or arousal.',
}
export const cognitiveDisclaimer = 'These states are EEG-derived estimates generated by Cortex and are not clinical assessments.'

export default function CognitiveStateInfo({ state }: { state: keyof typeof descriptions }) {
  const id = useId()
  const trigger = useRef<HTMLButtonElement>(null)
  const pinned = useRef(false)
  const timer = useRef<ReturnType<typeof setTimeout> | undefined>(undefined)
  const [position, setPosition] = useState<{ left: number; top: number } | null>(null)
  function cancelClose() { clearTimeout(timer.current) }
  function show() {
    cancelClose()
    const rect = trigger.current?.getBoundingClientRect()
    if (!rect) return
    const width = Math.min(260, window.innerWidth - 32)
    setPosition({ left: Math.max(16, Math.min(rect.left, window.innerWidth - width - 16)), top: rect.bottom + 110 < window.innerHeight ? rect.bottom + 4 : Math.max(16, rect.top - 110) })
  }
  function scheduleClose() {
    cancelClose()
    timer.current = setTimeout(() => { if (!pinned.current && document.activeElement !== trigger.current) setPosition(null) }, 120)
  }
  useEffect(() => () => clearTimeout(timer.current), [])
  useEffect(() => {
    if (!position) return
    const close = () => { pinned.current = false; setPosition(null) }
    const key = (event: KeyboardEvent) => { if (event.key === 'Escape') close() }
    document.addEventListener('keydown', key)
    window.addEventListener('resize', close)
    window.addEventListener('scroll', close, true)
    return () => { document.removeEventListener('keydown', key); window.removeEventListener('resize', close); window.removeEventListener('scroll', close, true) }
  }, [position])
  return <span className={styles.root}>
    <button ref={trigger} type="button" className={styles.trigger} aria-label={`About ${state}`} aria-describedby={position ? id : undefined}
      onMouseEnter={show} onMouseLeave={scheduleClose} onFocus={show}
      onBlur={() => { pinned.current = false; setPosition(null) }}
      onClick={() => { pinned.current = !pinned.current; if (pinned.current) show(); else setPosition(null) }}><Info size={14} aria-hidden="true" /></button>
    {position && createPortal(<span id={id} role="tooltip" className={styles.tooltip} style={position} onMouseEnter={cancelClose} onMouseLeave={scheduleClose}>{descriptions[state]}</span>, document.body)}
  </span>
}
